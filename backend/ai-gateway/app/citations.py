"""
Citations router and formatting utilities for the AI Gateway.

Provides endpoints and verification helpers to match reference documents
and guarantee every Copilot response carries at least one structured citation.
Supported source types:
- Asset
- Exposure
- Risk Score
- Policy
- Report
- Audit Log
- KB Article (planned, no tool yet)

A placeholder citation of type "none" is used when no real source exists.
"""

from typing import Any, Dict, List, Optional
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

router = APIRouter(prefix="/citations", tags=["Citations"])

VALID_SOURCE_TYPES = {
    "asset",
    "exposure",
    "risk_score",
    "policy",
    "report",
    "audit_log",
    "kb_article",
    "none",
    "reference",
    "document",
}


class CitationRequest(BaseModel):
    text: str
    source_documents: List[str]


class CitationResponse(BaseModel):
    status: str
    citations: List[Dict[str, Any]]
    matched_count: int


def build_citation(
    source_type: str,
    id_ref: str,
    title: Optional[str] = None,
    url: Optional[str] = None,
) -> Dict[str, Any]:
    """Create a normalized citation dictionary."""
    normalized_type = source_type.lower()
    if normalized_type not in VALID_SOURCE_TYPES:
        normalized_type = "reference"

    return {
        "id": f"cit-{normalized_type}-{id_ref}",
        "type": normalized_type,
        "id_ref": id_ref,
        "title": title or f"{source_type.title()} Reference {id_ref}",
        "url": url or f"/{normalized_type}s/{id_ref}",
    }


def ensure_response_citation(
    citations: Optional[List[Dict[str, Any]]],
    question: str = "",
    answer: str = "",
) -> List[Dict[str, Any]]:
    """
    Ensure every AI Gateway response carries at least one structured citation.
    If none were generated by tools or upstream models, adds an explicit
    placeholder (type "none") so callers can tell that no real source exists.
    """
    result = list(citations) if citations else []
    if not result:
        result.append({
            "id": "cit-none",
            "type": "none",
            "id_ref": "none",
            "title": "No source available",
            "url": None,
        })
    return result


@router.post("/", response_model=CitationResponse)
def generate_citations(payload: CitationRequest):
    """
    Match source documents against provided text and return matched citations.
    """
    try:
        matched_citations = []
        text_lower = payload.text.lower()
        for i, doc in enumerate(payload.source_documents):
            if doc.lower() in text_lower:
                matched_citations.append({
                    "id": f"citation-{i+1:03d}",
                    "name": doc,
                    "type": "reference",
                    "description": f"Verified citation reference for: {doc}",
                    "status": "active",
                    "url": f"/docs/{doc.lower().replace(' ', '-')}",
                })
        return {
            "status": "success",
            "citations": matched_citations,
            "matched_count": len(matched_citations),
        }
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))
